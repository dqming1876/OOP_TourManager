"""Contracts between business services and their interchangeable repositories."""

from typing import Protocol

from .domain import Booking, Departure, Tour, Transition

Row = dict[str, object]


class Database(Protocol):
    async def first(self, sql: str, *values) -> Row | None: ...
    async def all(self, sql: str, *values) -> list[Row]: ...
    async def execute(self, sql: str, *values) -> int: ...
    async def batch(self, statements: list[tuple[str, tuple]]) -> list[list[Row]]: ...


class AccountsPort(Protocol):
    async def claim_attempt(self, key: str, now: int) -> Row | None: ...
    async def clear_attempts(self, key: str, expires_at: int) -> None: ...
    async def find_public(self, account_id: str) -> Row | None: ...
    async def find_by_username(self, username: str) -> Row | None: ...
    async def create(self, account_id: str, username: str, name: str, password_hash: str, salt: str) -> bool: ...
    async def update_profile(self, account_id: str, profile: Row) -> None: ...


class BookingPort(Protocol):
    async def list_bookings(self, user_id: str | None) -> list[Row]: ...
    async def payment_history(self, booking_id: str) -> list[Row]: ...
    async def place_booking(self, booking: Booking, today: str) -> bool: ...
    async def update_booking(self, booking_id: str, rule: Transition, owner_id: str | None, today: str) -> bool: ...


class TourCatalogPort(Protocol):
    async def catalog(self, include_hidden: bool) -> list[Row]: ...
    async def save_tour(self, tour: Tour, create: bool) -> bool: ...
    async def set_visibility(self, tour_id: str, hidden: bool) -> bool: ...
    async def create_departure(self, departure: Departure) -> bool: ...
    async def change_departure_capacity(self, departure: Departure) -> bool: ...
    async def remove_departure(self, tour_id: str, day: str) -> bool: ...


class ReportsPort(Protocol):
    async def load(self, start: str, end: str, tour_id: str, today: str) -> dict[str, list[Row]]: ...
